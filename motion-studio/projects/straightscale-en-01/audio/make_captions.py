"""Caption chunks from audio/words.json -> assets/data.js (CAPTIONS, LINES, WORDS). Chunks are (word count, display text, highlight).
Display text may write numbers as digits; the word count ties each chunk to the spoken words, checked in code."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
W = json.load(open(os.path.join(HERE, "words.json")))["words"]
L = json.load(open(os.path.join(HERE, "lines.json")))
SPEC = {
    2: [(2, "59 owners", ["59"]), (3, "in our research", []), (4, "describe this exact cycle.", ["exact", "cycle."])],
    3: [(3, "The usual advice?", []), (2, "Post more.", []), (2, "Prospect more.", [])],
    4: [(3, "But your channel", []), (2, "still works.", ["still", "works."]), (2, "The replies", []), (2, "still come.", ["still", "come."])],
    5: [(4, "The months go missing", ["missing"]), (3, "after the reply.", ["after", "the", "reply."])],
    6: [(2, "Here's the", []), (2, "3-step check.", ["3-step"])],
    7: [(3, "1. Write down", ["1."]), (4, "replies and new clients", []), (4, "for each of the", []), (3, "last six months.", ["six", "months."])],
    8: [(4, "2. Circle the months", ["2."]), (3, "where replies held,", ["held,"]), (3, "but clients dropped.", ["dropped."]), (2, "That gap", []), (3, "is your leak.", ["leak."])],
    9: [(2, "3. Today,", ["3."]), (4, "answer every open reply", []), (5, "with two real call times.", ["two", "real", "call", "times."]), (4, "Not “let me know.”", [])],
    11: [(3, "Fix the step,", ["Fix", "the", "step,"]), (3, "not the channel.", [])],
}
by_line = {}
for w in W: by_line.setdefault(w["line"], []).append(w)
caps = []
for ln in L["lines"]:
    i = ln["i"]
    if i not in SPEC: continue
    ws = by_line[i]
    assert sum(n for n, _, _ in SPEC[i]) == len(ws), (i, len(ws), [x["w"] for x in ws])
    k = 0
    for n, text, hi in SPEC[i]:
        grp = ws[k:k + n]; k += n
        caps.append({"line": i, "t0": round(grp[0]["s"] - 0.06, 3), "t1": None, "text": text, "hi": hi,
                     "spoken": " ".join(g["w"] for g in grp)})
for a, b in zip(caps, caps[1:]):
    a["t1"] = round(b["t0"] if b["line"] == a["line"] else min(b["t0"], next(l["e"] for l in L["lines"] if l["i"] == a["line"]) + 0.35), 3)
caps[-1]["t1"] = round(L["lines"][-1]["e"] + 0.5, 3)
lines = {l["i"]: [l["s"], l["e"]] for l in L["lines"]}
out = "// generated by audio/make_captions.py from audio/words.json; do not edit by hand\n"
out += "export const CAPTIONS = " + json.dumps(caps) + ";\n"
out += "export const LINES = " + json.dumps(lines) + ";\n"
out += "export const WORDS = " + json.dumps([[w["w"], w["s"], w["e"], w["line"]] for w in W]) + ";\n"
out += "export const VO_DURATION = " + json.dumps(L["duration"]) + ";\n"
open(os.path.join(ROOT, "assets", "data.js"), "w").write(out)
print(len(caps), "captions"); [print(c["line"], c["t0"], c["t1"], c["text"], "|", c["spoken"]) for c in caps]
